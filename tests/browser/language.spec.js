const {test,expect}=require('@playwright/test')
test('language switch persists and localizes navigation, forms and animation',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/#/')
 await expect(page.locator('html')).toHaveAttribute('lang','zh-CN')
 await expect(page.locator('.nav-links')).toContainText('验证流程')
 await page.locator('.language-switcher select').selectOption('en')
 await expect(page.locator('html')).toHaveAttribute('lang','en')
 await expect(page.locator('.nav-links')).toContainText('Verification workflow')
 await expect(page.locator('[data-action="auto"]')).toHaveText('Alternate languages')
 await page.goto('/#/projects')
 await expect(page.locator('h1')).toHaveText('Projects')
 await page.reload()
 await expect(page.locator('html')).toHaveAttribute('lang','en')
 await expect(page.locator('h1')).toHaveText('Projects')
 await page.getByRole('button',{name:'＋ New project',exact:true}).click()
 await expect(page.getByText('Project name',{exact:true})).toBeVisible()
 await page.locator('.language-switcher select').selectOption('zh-CN')
 await expect(page.getByText('项目名称',{exact:true})).toBeVisible()
 expect(errors).toEqual([])
})
test('code content stays unchanged when switching language in a benchmark',async({page})=>{
 await page.goto('/#/benchmarks/live24?file=code2_103.c')
 const code=page.locator('.ide-editor textarea')
 await expect(code).toBeVisible()
 const original=await code.inputValue()
 await page.locator('.language-switcher select').selectOption('en')
 await expect(page.getByRole('button',{name:'Original source',exact:true})).toBeVisible()
 expect(await code.inputValue()).toBe(original)
 await page.locator('.language-switcher select').selectOption('zh-CN')
 await expect(page.getByRole('button',{name:'原始源码',exact:true})).toBeVisible()
 expect(await code.inputValue()).toBe(original)
})
test('annotated assumptions are blocked before submission with an original-source alternative',async({page})=>{
 await page.goto('/#/benchmarks/live25?file=array-cav19_array_init_nondet_vars.c')
 await page.getByRole('button',{name:'带规约代码',exact:true}).click()
 await page.getByRole('button',{name:'▷ 验证',exact:true}).click()
 await expect(page.getByText('该代码含未证明假设，直接验证不会执行。',{exact:false})).toBeVisible()
 await expect(page.getByRole('button',{name:'开始验证',exact:true})).toBeDisabled()
 await page.getByRole('button',{name:'改用原始源码生成并验证',exact:true}).click()
 await expect(page.getByRole('combobox',{name:'重跑方式',exact:true})).toHaveValue('generate')
 await expect(page.getByRole('button',{name:'开始验证',exact:true})).toBeEnabled()
 // No task is submitted, and no model call is made by this test.
})
