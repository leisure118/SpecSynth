"""Stable ports implemented by adapters.

Application services type-hint these protocols so adapters (JSON files, host
Frama-C, external Agent CLIs) can be replaced without rewriting use cases.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol


class RunStore(Protocol):
    def create_upload(self, filename: str, payload: bytes) -> dict[str, Any]: ...
    def create_bundle_upload(self, files: list[dict[str, Any]], root_dir: str | None = None) -> dict[str, Any]: ...
    def read_upload(self, file_id: str) -> dict[str, Any] | None: ...
    def create_task(self, task): ...
    def write_task(self, task) -> None: ...
    def read_task(self, task_id: str): ...
    def write_result(self, task_id: str, result: dict[str, Any]) -> None: ...
    def read_result(self, task_id: str) -> dict[str, Any] | None: ...
    def list_tasks(self, limit: int = 20) -> list: ...
    def write_text_artifact(self, task_id: str, kind: str, name: str, content: str) -> None: ...
    def read_artifact_text(self, task_id: str, relative_path: str) -> dict[str, Any] | None: ...
    def list_artifacts(self, task_id: str) -> list[dict[str, Any]]: ...


class RunOrchestrator(Protocol):
    store: RunStore

    def submit(self, mode: str, payload): ...
    def overview(self) -> dict[str, Any]: ...
    def ensure_materialized(self, task_id: str): ...
    def recover_incomplete_tasks(self, limit: int = 40) -> int: ...


class AgentRuntime(Protocol):
    def generate(self, agent: str, prompt: str, directory: Path, timeout: int, model: str = "", sub_model: str = ""): ...
    def require_agent(self, agent: str) -> None: ...


class Verifier(Protocol):
    def preflight(self) -> tuple[bool, str]: ...
    def run_candidate(self, files: list[dict[str, str]], entry: str, mode: str, timeout_sec: int, workdir: Path, function: str | None = None) -> dict[str, Any]: ...
