const {test,expect}=require('@playwright/test')
for (const agent of ['codex','claude-code','deepseek-harness']) test(agent+' benchmark submits selected Qwen sub-agent without a paid run',async({page})=>{
 await page.goto('/#/benchmarks/live24?file=frama-c-wp-tutorial-en_10.c')
 await page.getByRole('button',{name:'▷ 验证',exact:true}).click()
 await page.getByRole('combobox',{name:'重跑方式',exact:true}).selectOption('generate')
 await page.getByRole('combobox',{name:'重跑 Agent',exact:true}).selectOption(agent)
 const sub=page.getByRole('combobox',{name:'Sub-agent 模型',exact:true})
 await expect(sub).toBeVisible()
 await sub.selectOption('qwen35-4b-mix64')
 let submitted
 await page.route('**/api/v1/benchmarks/live24/runs',async route=>{
  submitted=route.request().postDataJSON()
  await route.fulfill({status:422,contentType:'application/json',body:JSON.stringify({detail:'Preview only; no model call'})})
 })
 await page.getByRole('button',{name:'开始验证',exact:true}).click()
 await expect.poll(()=>submitted?.assistant?.sub_model).toBe('qwen35-4b-mix64')
 expect(submitted.assistant.agent).toBe(agent)
 await sub.selectOption('qwen35-9b-mix64')
 await page.getByRole('button',{name:'开始验证',exact:true}).click()
 await expect.poll(()=>submitted?.assistant?.sub_model).toBe('qwen35-9b-mix64')
 await sub.selectOption('')
 await page.getByRole('button',{name:'开始验证',exact:true}).click()
 await expect.poll(()=>submitted?.assistant?.sub_model).toBe('')
})
