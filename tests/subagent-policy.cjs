const assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
const fs=require('node:fs');
const os=require('node:os');
(async()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'subagent-policy-'));
 process.env.DSH_SUBAGENT_AUDIT=path.join(dir,'events.jsonl');process.env.DSH_PROGRESS_FILE=path.join(dir,'progress.jsonl');process.env.DSH_REQUIRE_SUBAGENT='1';
 const listeners={};const ctx={on:(name,fn)=>listeners[name]=fn};
 const {apply}=await import(pathToFileURL(path.resolve('engine/cli_plugins/subagent_audit.mjs')));apply(ctx);
 let guard,restriction;
 listeners['agent/created']({agent:{session:{header:{}},ctx:{tools:{guard:fn=>guard=fn}},options:{provider:'platform-api'}}});
 assert.match(guard({name:'write'}),/first delegate/);
 assert.equal(guard({name:'read'}),undefined);
 listeners['subagent/end']({id:'failed',stopReason:'error'});assert.ok(guard({name:'write'}));
 listeners['agent/created']({agent:{id:'child',session:{header:{origin:'subagent'}},options:{provider:'platform-subagent',model:'qwen35-9b-mix64'},ctx:{tools:{restrict:value=>restriction=value}}}});
 assert.deepEqual(restriction,{allow:[]});
 listeners['subagent/end']({id:'child',stopReason:'completed'});assert.equal(guard({name:'write'}),undefined);
 listeners['session/event']({}, {type:'tool/call',data:{callId:'verify1',name:'bash',arguments:{command:'python -m engine.harness_spectool verify --file main.c'}}});
 listeners['tools/result']({callId:'verify1',name:'bash',arguments:{command:'python -m engine.harness_spectool verify --file main.c'}},{isError:false,value:{exitCode:1}});
 listeners['tools/result']({callId:'proof-failed',name:'bash',arguments:{command:'verify main.c'}},{isError:false,value:{exitCode:0,stdout:{text:JSON.stringify({verified:false})}}});
 const rows=fs.readFileSync(process.env.DSH_PROGRESS_FILE,'utf8').trim().split('\n').map(JSON.parse);
 assert.equal(rows.at(-1).label,'Frama-C 验证');assert.equal(rows.at(-1).status,'failed');assert.equal(rows.at(-3).status,'running');assert.equal(rows.at(-1).detail,'证明尚未通过，请查看诊断');
 process.env.DSH_COMPACT_C='1';
 let mainRestriction;
 listeners['agent/created']({agent:{session:{header:{}},options:{provider:'platform-api'},ctx:{tools:{guard:()=>{},restrict:value=>mainRestriction=value}}}});
 assert.deepEqual(mainRestriction,{allow:['subagent','write']});
 delete process.env.DSH_COMPACT_C;
 fs.rmSync(dir,{recursive:true});console.log('Native child completion gates candidate writes; Qwen text-only scope preserved.');
})().catch(e=>{console.error(e);process.exitCode=1});
