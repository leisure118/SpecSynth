const {test,expect}=require('@playwright/test');
test('home result analysis includes all benchmark rates',async({page})=>{
 await page.goto('/#/');
 const results=page.locator('.vf-dataset-results');
 await expect(results.getByRole('link',{name:/LiveFMBench 2025/})).toBeVisible();
 for(const rate of ['63.1%','82.5%','69.0%','94.4%','66.9%','94.9%'])await expect(results.getByText(rate,{exact:true})).toBeVisible();
 await results.scrollIntoViewIfNeeded();
 await page.screenshot({path:'/tmp/benchmark-home-rates.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
test('benchmark three-column workspace supports file evidence and mobile panels',async({page})=>{
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('/#/projects');
 await page.getByRole('link').filter({has:page.getByRole('heading',{name:'LiveFMBench 2025',exact:true})}).click();
 await expect(page.getByRole('heading',{name:'LiveFMBench 2025 基准测试',exact:true})).toBeVisible();
 await expect(page.locator('.vf-benchmark-history-footer')).toBeVisible();
 const files=page.locator('.vf-bench-file-list');
 await page.getByLabel('搜索基准文件').fill('array-cav19_array_doub_access_init_const');
 await files.locator('.br-tree-file').first().click();
 await expect(page).toHaveURL(/file=array-cav19_array_doub_access_init_const.c/);
 await expect(page.getByText('无有效目标',{exact:true})).toBeVisible();
 await expect(page.locator('.vf-benchmark-code')).toBeVisible();
 await expect(page.getByLabel('源码版本')).toHaveValue('original');
 await page.getByLabel('搜索基准文件').fill('');
 await page.getByLabel('筛选验证状态').selectOption('flagged');
 await files.locator('.br-tree-file').first().click();
 await expect(page.locator('.vf-bench-detail .vf-panel-heading .vf-bench-status')).toHaveText('违规假设');
 await expect(page.locator('.vf-benchmark-code')).toBeVisible();
 await page.getByLabel('源码版本').selectOption('annotated');
 await expect(page.locator('.br-acsl-line')).not.toHaveCount(0);
 await expect(page.locator('.vf-bench-detail .vf-run-log')).toBeVisible();
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'↓ 下载 log'}).click();expect((await download).suggestedFilename()).toMatch(/\.wp\.txt$/);
 await page.screenshot({path:'/tmp/benchmark-workspace-desktop.png',fullPage:true});
 await page.reload();
 await expect(page.locator('.vf-bench-detail .vf-panel-heading .vf-bench-status')).toHaveText('违规假设');
 await page.setViewportSize({width:390,height:844});
 await page.locator('.vf-mobile-nav').getByRole('button',{name:'验证',exact:true}).click();
 await expect(page.locator('.vf-bench-detail')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'/tmp/benchmark-workspace-mobile.png',fullPage:true});
 await page.locator('.vf-mobile-nav').getByRole('button',{name:'文件',exact:true}).click();
 await expect(page.getByLabel('搜索基准文件')).toBeVisible();
});
test('single-case rerun opens configuration and displays saved real records',async({page})=>{
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('/#/benchmarks/autobench_v2?file=103.c');
 await expect(page.getByRole('button',{name:'▷ 重新验证',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'▷ 重新验证',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await expect(page.getByLabel('重跑方式')).toHaveValue('verify');
 await page.getByLabel('重跑方式').selectOption('generate');
 await expect(page.getByLabel('重跑 Agent')).toBeVisible();
 await expect(page.getByText('提交后将把此案例源码及选中 Skill 指令发送给所选模型服务。')).toBeVisible();
 await page.getByRole('button',{name:'Close this dialog'}).click();
 const history=page.locator('.br-rerun-history');
 await expect(history.getByRole('button').filter({hasText:'直接验证'}).first()).toBeVisible();
 await history.getByRole('button').filter({hasText:'直接验证'}).first().click();
 await expect(page.getByRole('link',{name:'完整结果与源码、配置、候选工件 ↗'})).toBeVisible();
 await expect(page.getByRole('button',{name:'查看输入'})).toBeVisible();
 await page.screenshot({path:'/tmp/benchmark-rerun-evidence.png',fullPage:true});
 await history.getByRole('button',{name:'查看原始实验'}).click();
 await expect(page.getByRole('button',{name:'查看输入'})).toHaveCount(0);
 await page.goto('/#/benchmarks/live25?file=array-cav19_array_doub_access_init_const.c');
 await expect(page.getByRole('button',{name:'▷ 重新验证',exact:true})).toBeEnabled();
 await expect(page.getByLabel('源码版本')).toHaveValue('original');
});
